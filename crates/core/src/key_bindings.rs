//! Portable parser for user-editable mpv key mapping profiles.

use std::fmt;

const APP_DIRECTIVE: &str = "#@iina";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ActionKind {
    Mpv,
    Riina,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Mapping {
    pub key: String,
    pub action: String,
    pub kind: ActionKind,
    pub comment: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(default, deny_unknown_fields)]
pub struct Settings {
    pub current_profile: String,
    pub use_system_media_controls: bool,
    pub display_raw_values: bool,
}

impl Default for Settings {
    fn default() -> Self {
        Self {
            current_profile: "IINA Default".into(),
            use_system_media_controls: true,
            display_raw_values: false,
        }
    }
}

impl Settings {
    pub fn validate(&self) -> Result<(), &'static str> {
        let profile = self.current_profile.as_str();
        if profile.trim().is_empty()
            || profile.len() > 120
            || profile.trim() != profile
            || profile.chars().any(|character| {
                character.is_control()
                    || matches!(
                        character,
                        '<' | '>' | ':' | '"' | '/' | '\\' | '|' | '?' | '*'
                    )
            })
        {
            return Err("Invalid input profile name");
        }
        Ok(())
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParseError {
    line: usize,
    reason: &'static str,
}

impl ParseError {
    pub const fn line(&self) -> usize {
        self.line
    }

    pub const fn reason(&self) -> &'static str {
        self.reason
    }
}

impl fmt::Display for ParseError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            formatter,
            "invalid key mapping on line {}: {}",
            self.line, self.reason
        )
    }
}

impl std::error::Error for ParseError {}

pub fn parse(input: &str) -> Result<Vec<Mapping>, ParseError> {
    input
        .lines()
        .enumerate()
        .filter_map(|(line_index, line)| {
            let line_number = line_index + 1;
            let mut line = line.trim();
            if line.is_empty() {
                return None;
            }

            let kind = if let Some(directive) = line.strip_prefix(APP_DIRECTIVE) {
                line = directive.trim_start();
                ActionKind::Riina
            } else if line.starts_with('#') {
                return None;
            } else {
                ActionKind::Mpv
            };

            let (mapping, comment) = match line.split_once('#') {
                Some((mapping, comment)) => (mapping.trim_end(), Some(comment.trim().to_owned())),
                None => (line, None),
            };
            let Some((key, action)) = mapping.split_once(char::is_whitespace) else {
                return Some(Err(ParseError {
                    line: line_number,
                    reason: "expected a key followed by an action",
                }));
            };
            let key = key.trim();
            let action = action.trim();
            if key.is_empty() || action.is_empty() {
                return Some(Err(ParseError {
                    line: line_number,
                    reason: "key and action must not be empty",
                }));
            }

            Some(Ok(Mapping {
                key: key.to_owned(),
                action: action.to_owned(),
                kind,
                comment: comment.filter(|value| !value.is_empty()),
            }))
        })
        .collect()
}

pub fn serialize(mappings: &[Mapping]) -> Result<String, ParseError> {
    let mut output = String::from("# Generated by riina\n\n");
    for (index, mapping) in mappings.iter().enumerate() {
        if mapping.key.trim().is_empty()
            || mapping.action.trim().is_empty()
            || mapping.key.contains(['\n', '\r', '#'])
            || mapping.action.contains(['\n', '\r'])
            || mapping
                .comment
                .as_ref()
                .is_some_and(|comment| comment.contains(['\n', '\r']))
        {
            return Err(ParseError {
                line: index + 1,
                reason: "mapping fields contain an unsupported value",
            });
        }

        if mapping.kind == ActionKind::Riina {
            output.push_str(APP_DIRECTIVE);
            output.push(' ');
        }
        output.push_str(mapping.key.trim());
        output.push(' ');
        output.push_str(mapping.action.trim());
        if let Some(comment) = mapping
            .comment
            .as_deref()
            .filter(|value| !value.trim().is_empty())
        {
            output.push_str("   #");
            output.push_str(comment.trim());
        }
        output.push('\n');
    }
    Ok(output)
}

/// Convert one user profile action to the argument vector passed to libmpv.
/// Input flags describe mpv's input layer rather than a command and are removed
/// here; shell parsing is deliberately avoided so profile text is never executed
/// by the operating system.
pub fn mpv_action_args(action: &str) -> Result<Vec<String>, String> {
    if action.is_empty() || action.len() > 8192 || action.contains('\0') {
        return Err("Key binding action is empty, oversized, or contains a NUL byte".into());
    }

    let mut args = Vec::new();
    let mut current = String::new();
    let mut quote = None;
    let mut escaped = false;
    let mut token_started = false;
    for character in action.chars() {
        if escaped {
            current.push(character);
            escaped = false;
            token_started = true;
            continue;
        }
        if character == '\\' {
            escaped = true;
            token_started = true;
            continue;
        }
        if let Some(delimiter) = quote {
            if character == delimiter {
                quote = None;
            } else {
                current.push(character);
            }
            token_started = true;
            continue;
        }
        match character {
            '"' | '\'' => {
                quote = Some(character);
                token_started = true;
            }
            value if value.is_whitespace() => {
                if token_started {
                    args.push(std::mem::take(&mut current));
                    token_started = false;
                    if args.len() > 64 {
                        return Err("Key binding action exceeds the 64 argument limit".into());
                    }
                }
            }
            value => {
                current.push(value);
                token_started = true;
            }
        }
        if current.len() > 4096 {
            return Err("Key binding argument exceeds the 4 KiB limit".into());
        }
    }
    if escaped || quote.is_some() {
        return Err("Key binding action has an unfinished escape or quote".into());
    }
    if token_started {
        args.push(current);
    }
    if args.len() > 64 {
        return Err("Key binding action exceeds the 64 argument limit".into());
    }
    if args.iter().any(|argument| argument.len() > 4096) {
        return Err("Key binding argument exceeds the 4 KiB limit".into());
    }

    while args.first().is_some_and(|argument| {
        matches!(
            argument.as_str(),
            "{default}"
                | "no-osd"
                | "osd-bar"
                | "osd-msg"
                | "osd-auto"
                | "repeatable"
                | "raw"
                | "async"
        )
    }) {
        args.remove(0);
    }
    if args
        .first()
        .is_some_and(|argument| argument.starts_with('{') && argument.ends_with('}'))
    {
        return Err("Key binding uses an unsupported input section".into());
    }
    if args.is_empty() {
        return Err("Key binding action contains no mpv command".into());
    }
    if matches!(args[0].as_str(), "run" | "subprocess") {
        return Err("Key binding actions cannot launch external processes".into());
    }
    Ok(args)
}

/// Convert an input mapping that chains commands with semicolons into separate
/// libmpv command argument lists. A semicolon inside a quoted or escaped token
/// remains data, matching input.conf's command separator behavior.
pub fn mpv_action_commands(action: &str) -> Result<Vec<Vec<String>>, String> {
    if action.is_empty() || action.len() > 8192 || action.contains('\0') {
        return Err("Key binding action is empty, oversized, or contains a NUL byte".into());
    }

    let mut commands = Vec::new();
    let mut current = String::new();
    let mut quote = None;
    let mut escaped = false;
    for character in action.chars() {
        if escaped {
            current.push(character);
            escaped = false;
            continue;
        }
        if character == '\\' {
            current.push(character);
            escaped = true;
            continue;
        }
        if let Some(delimiter) = quote {
            current.push(character);
            if character == delimiter {
                quote = None;
            }
            continue;
        }
        match character {
            '"' | '\'' => {
                quote = Some(character);
                current.push(character);
            }
            ';' => {
                push_mpv_action_command(&mut commands, &mut current)?;
            }
            _ => current.push(character),
        }
    }
    if escaped || quote.is_some() {
        return Err("Key binding action has an unfinished escape or quote".into());
    }
    push_mpv_action_command(&mut commands, &mut current)?;
    if commands.is_empty() {
        return Err("Key binding action contains no mpv command".into());
    }
    Ok(commands)
}

fn push_mpv_action_command(
    commands: &mut Vec<Vec<String>>,
    current: &mut String,
) -> Result<(), String> {
    if current.trim().is_empty() {
        return Err("Key binding action contains an empty command".into());
    }
    if commands.len() >= 32 {
        return Err("Key binding action exceeds the 32 command limit".into());
    }
    commands.push(mpv_action_args(current.trim())?);
    current.clear();
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_plain_and_application_directives_with_comments() {
        let mappings = parse(
            "# profile note\nSPACE cycle pause\n#@iina Meta+3 fit-to-screen # fit the player\n",
        )
        .unwrap();
        assert_eq!(mappings.len(), 2);
        assert_eq!(mappings[0].kind, ActionKind::Mpv);
        assert_eq!(mappings[0].action, "cycle pause");
        assert_eq!(mappings[1].kind, ActionKind::Riina);
        assert_eq!(mappings[1].key, "Meta+3");
        assert_eq!(mappings[1].comment.as_deref(), Some("fit the player"));
    }

    #[test]
    fn serialization_round_trips_order_and_action_kinds() {
        let mappings = vec![
            Mapping {
                key: "SPACE".into(),
                action: "cycle pause".into(),
                kind: ActionKind::Mpv,
                comment: Some("play or pause".into()),
            },
            Mapping {
                key: "Meta+3".into(),
                action: "fit-to-screen".into(),
                kind: ActionKind::Riina,
                comment: None,
            },
        ];
        let encoded = serialize(&mappings).unwrap();
        assert_eq!(parse(&encoded).unwrap(), mappings);
    }

    #[test]
    fn rejects_incomplete_and_multiline_mappings() {
        assert_eq!(parse("SPACE").unwrap_err().line(), 1);
        let invalid = Mapping {
            key: "SPACE".into(),
            action: "cycle pause\nSTOP quit".into(),
            kind: ActionKind::Mpv,
            comment: None,
        };
        assert!(serialize(&[invalid]).is_err());
    }

    #[test]
    fn settings_match_reference_defaults_and_reject_unsafe_profile_names() {
        let settings = Settings::default();
        assert_eq!(settings.current_profile, "IINA Default");
        assert!(settings.use_system_media_controls);
        assert!(!settings.display_raw_values);
        assert!(
            Settings {
                current_profile: "../external".into(),
                ..settings
            }
            .validate()
            .is_err()
        );
    }

    #[test]
    fn key_binding_commands_cannot_launch_external_processes() {
        assert!(mpv_action_commands("run calc.exe").is_err());
        assert!(mpv_action_commands("subprocess calc.exe").is_err());
        assert_eq!(
            mpv_action_commands("seek 5; show-text 'safe; value'").unwrap(),
            [vec!["seek", "5"], vec!["show-text", "safe; value"],]
        );
    }
}
